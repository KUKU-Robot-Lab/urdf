TOKEN_INERTIA = 1e-7

# ★Measured hand payloads (kg, per hand, everything past the wrist flange) that the
#   vendor link masses must add up to. DG-5F: user scale measurement 1.763 kg vs vendor
#   URDF 1.685 kg (4.6 % low; sim2real/docs/NEXT_SESSION_RIGHT_2026-08-31.md). The
#   vendor masses are round numbers with no per-part breakdown, so every hand link
#   (and its inertia tensor - same geometry) is scaled by one factor. Assets not
