HAND_MASS_TARGET_KG = {"openarm_dg5f-m_bi": 1.763}


def scale_hand_masses(root: ET.Element, target_kg: float) -> dict[str, float]:
    """Scale every ``*_hl_*`` inertial per side so the hand sums to ``target_kg``."""
    factors: dict[str, float] = {}
    for side in ("r", "l"):
        links = [l for l in root.findall("link")
                 if (l.get("name") or "").startswith(f"{side}_hl_") and l.find("inertial") is not None]
        total = sum(float(l.find("inertial/mass").get("value")) for l in links)
        if total <= 0:
            raise ValueError(f"{side} hand has no mass to scale")
        factor = target_kg / total
        for link in links:
            mass = link.find("inertial/mass")
            mass.set("value", f"{float(mass.get('value')) * factor:.6g}")
            inertia = link.find("inertial/inertia")
            if inertia is not None:
                for key, value in list(inertia.attrib.items()):
                    inertia.set(key, f"{float(value) * factor:.6g}")
        factors[side] = factor
    return factors


