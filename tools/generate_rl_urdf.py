# ★A URDF link without <inertial> is a "massless frame", but the USD import keeps
#   fixed joints unmerged (tip sensors / palm frames must stay bodies), so every such
#   frame becomes a rigid body - and PhysX gives a body with no mass 1.0 kg (measured
#   2026-09-02: 4 kg of ghost mass at the fingertips, j7 sag 11° vs 4° real). Writing
#   0 does not help either (PhysX rejects zero mass -> 1.0 kg again), so the frames
#   get a token 1e-5 kg (user-set, 2026-09-05: the same URDF feeds fabric/PD models
#   where a zero mass breaks the dynamics) here, in the URDF itself, and every
#   consumer (USD importer, fabric generators, sim2real models) sees the same value.
